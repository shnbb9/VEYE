"""The hashed dependency locks agree with pyproject.toml.

Both API images and CI install only from requirements/*.lock with
`pip --require-hashes` (defect U-4: unpinned ranges resolved from the index on
every build, so two builds of one commit could differ, and one failed on a
transient index fault). The locks are regenerated by
platform/scripts/lock-api-deps.ps1. This test fails when pyproject.toml has
been edited and the locks were not: every declared dependency of each lock's
set must be pinned there, inside its declared range, and every pin must carry
at least one hash.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

API = Path(__file__).resolve().parents[1]
PYPROJECT = tomllib.loads((API / "pyproject.toml").read_text(encoding="utf-8"))["project"]

LOCKS = {
    "dev.lock": ("ai",),
    "production.lock": ("gemini", "gcs"),
    "ci.lock": ("test", "ai"),
}


def _pins(lock: Path) -> dict[str, tuple[str, int]]:
    """{name: (version, hash count)} from a uv/pip-compile hashed lock."""
    pins: dict[str, tuple[str, int]] = {}
    current = None
    for line in lock.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^([A-Za-z0-9_.\-\[\],]+)==([^\s;\\]+)", line)
        if match:
            current = canonicalize_name(match.group(1).split("[")[0])
            pins[current] = (match.group(2), 0)
        elif current and "--hash=sha256:" in line:
            version, count = pins[current]
            pins[current] = (version, count + 1)
    return pins


@pytest.mark.parametrize("lock_name, extras", LOCKS.items())
def test_every_declared_dependency_is_locked_inside_its_range(lock_name, extras):
    lock = API / "requirements" / lock_name
    assert lock.exists(), f"{lock_name} is missing: run platform/scripts/lock-api-deps.ps1"
    pins = _pins(lock)
    declared = list(PYPROJECT["dependencies"])
    for extra in extras:
        declared += PYPROJECT["optional-dependencies"][extra]
    for line in declared:
        requirement = Requirement(line)
        name = canonicalize_name(requirement.name)
        assert name in pins, f"{requirement.name} is declared but not in {lock_name} — re-lock"
        version, _ = pins[name]
        assert requirement.specifier.contains(version, prereleases=True), (
            f"{lock_name} pins {requirement.name}=={version}, outside {requirement.specifier} — re-lock")


@pytest.mark.parametrize("lock_name", LOCKS)
def test_every_pin_carries_a_hash(lock_name):
    pins = _pins(API / "requirements" / lock_name)
    assert len(pins) > 30, f"{lock_name} looks empty"
    unhashed = [name for name, (_, hashes) in pins.items() if hashes == 0]
    assert unhashed == [], f"{lock_name} has pins without a hash: {unhashed}"


def test_the_images_install_only_from_the_locks():
    """Neither Dockerfile may fall back to resolving ranges from the index."""
    docker = API.parent / "docker"
    for dockerfile, lock in (("api.Dockerfile", "dev.lock"), ("api.production.Dockerfile", "production.lock")):
        text = (docker / dockerfile).read_text(encoding="utf-8")
        installs = [line for line in text.splitlines() if re.search(r"\bpip install\b", line) and not line.lstrip().startswith("#")]
        assert installs, f"{dockerfile} installs nothing"
        for line in installs:
            assert "--require-hashes" in line and f"requirements/{lock}" in line, f"{dockerfile}: {line.strip()}"

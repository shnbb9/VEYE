from datetime import datetime
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.policies.richtext import RichDoc


class HealthPermissionEventOut(BaseModel):
    """One transition, as evidence. Carries no health value of its own — only
    that a decision was made, by whom, from where, and against which wording."""

    id: UUID
    from_state: str
    to_state: str
    actor: str
    actor_name: str
    source: str
    policy_version: str
    created_at: datetime
    # Present on decisions made against published terms (V2 §4.4).
    terms_version: int | None = None
    terms_hash: str | None = None
    scope: list[str] | None = None
    purpose: str | None = None
    recipient: str | None = None
    expiry_rule: str | None = None
    note: str | None = None


class TermsOut(BaseModel):
    """What a member reads before deciding. HTML here is generated by VEYE
    from a validated document tree, every text node escaped."""

    version: int
    label: str
    hash: str
    published_at: datetime | None
    published_by: str
    summary_html: str
    summary_text: str
    details_html: str
    purpose: str
    recipient: str
    categories: list[str]
    companion_use: str
    expiry_rule: str
    withdrawal: str
    not_covered: str
    decline_effect: str


class OpenRequestOut(BaseModel):
    ref: str
    requested_at: datetime | None
    requested_by_name: str
    automatic: bool


class DeliveryStatusOut(BaseModel):
    status: str          # queued | sending | retry | sent | failed | skipped
    attempts: int
    last_error: str | None
    sent_at: datetime | None
    next_attempt_at: datetime | None
    to_email: str


class HealthPermissionOut(BaseModel):
    state: str
    state_label: str
    shares_health_data: bool
    # What the member last decided against, and what the words say today. When
    # they differ, the member decided against older wording.
    policy_version: str
    current_policy_version: str
    explanation: str
    requested_at: datetime | None
    requested_by_name: str
    decided_at: datetime | None
    revoked_at: datetime | None
    events: list[HealthPermissionEventOut] = []
    terms: TermsOut | None = None
    open_request: OpenRequestOut | None = None
    email_verified: bool | None = None
    # The console's view only.
    can_request: bool | None = None
    cannot_request_reason: str | None = None
    requires_reason: bool | None = None
    next_request_at: datetime | None = None
    delivery: DeliveryStatusOut | None = None


class DecisionIn(BaseModel):
    """The terms the member was shown. A decision against words that are no
    longer current is refused rather than credited to the new ones."""

    model_config = ConfigDict(extra="forbid")
    terms_version: int = Field(ge=0)
    terms_hash: str = Field(min_length=64, max_length=64)
    request_ref: str | None = Field(default=None, max_length=64)


class RequestIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    reason: str | None = Field(default=None, max_length=300)


class NotificationIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    mode: str
    resend_interval_hours: int
    sender_name: str = Field(max_length=60)


class TemplateIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    subject: str = Field(max_length=180)
    body: RichDoc


class TermsIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    summary: RichDoc
    details: RichDoc
    purpose: str = Field(max_length=300)
    recipient: str = Field(max_length=160)
